    w("-- por NOMBRE normalizado: mayusculas, sin acentos, espacios colapsados.")
    w("--")
    w("-- Devuelve 8 resultados:")
    w("--   1. Resumen de conteos")
    w("--   2. Nombres ambiguos: el mismo nombre repetido en el catalogo actual")
    w("--   3. Los del archivo que YA existen -> el import debe ACTUALIZARLOS")
    w("--   4. Los del archivo que NO existen -> se insertan nuevos")
    w("--   5. Los que ya estan cargados y NO vienen en el archivo -> tu decides")
    w("--   6. Como esta hoy el catalogo: tax_mode e impuestos enlazados")
    w("--   7. Nombres repetidos DENTRO del archivo")
    w("--   8. Categorias: cuales del archivo ya existen y cuales se crearian")
    w("-- =============================================================================")
    w("")
    w("begin;")
