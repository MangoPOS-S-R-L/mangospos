def q(s):
    if s is None or s == "":
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"


def num(x):
    return "NULL" if x is None else ("%.2f" % float(x))


def area_of(sku, cat):
    if sku in OVERRIDES:
        return OVERRIDES[sku]
    if cat in BAR_CATS:
        return "B"
    if cat in KITCHEN_CATS:
        return "K"
    if cat in MIXED_CATS:
        raise SystemExit(
            "sku %r (%s) es de categoría mixta y no tiene override de área" % (sku, cat)
        )
    raise SystemExit("categoría sin clasificar: %r (sku %s)" % (cat, sku))


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Desktop/productos.csv")
    with open(src, encoding="utf-8-sig", newline="") as fh:
        rows = list(csv.DictReader(fh))

    items = []
    for r in rows:
        sku = (r["Codigo del Producto"] or "").strip()
        name = (r["Descripcion del Producto"] or "").strip()
        cat = (r["Categoria"] or "").strip()
        cost = float(r["Costo"] or 0)
        price = float(r["Precio"] or 0)
        if not sku or not name:
            continue
        items.append({
            "sku": sku,
            "name": unicodedata.normalize("NFC", name),
            "cat": unicodedata.normalize("NFC", cat) or None,
            "cost": cost if cost > 0 else None,   # 0.00 -> NULL (sin costo)
            "price": price,
            "area": area_of(sku, cat),
        })

    dups = {i["sku"] for i in items}
    if len(dups) != len(items):
        raise SystemExit("hay SKUs duplicados en el CSV")

    cats = sorted({i["cat"] for i in items if i["cat"]})
    n_bar = sum(1 for i in items if "B" in i["area"])
    n_kit = sum(1 for i in items if "K" in i["area"])
    n_both = sum(1 for i in items if i["area"] == "KB")

    _write_diag()
    _write_rollback(items)
    _write_import(items, cats, src)
    _write_areas(items, n_bar, n_kit, n_both)
    _write_compare(items)
    _write_resumen(items)

    print("productos : %d" % len(items), file=sys.stderr)
    print("categorias: %d" % len(cats), file=sys.stderr)
    print("bar %d | cocina %d | ambas %d" % (n_bar, n_kit, n_both), file=sys.stderr)
    print("sin precio: %d" % sum(1 for i in items if i["price"] == 0), file=sys.stderr)
    print("sin costo : %d" % sum(1 for i in items if i["cost"] is None), file=sys.stderr)


