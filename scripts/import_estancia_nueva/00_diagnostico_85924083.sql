         upper(regexp_replace(translate(btrim(a.nombre),   'áéíóúÁÉÍÓÚñÑ', 'aeiouAEIOUnN'), '\s+', ' ', 'g')) as n1,
         upper(regexp_replace(translate(btrim(a.original), 'áéíóúÁÉÍÓÚñÑ', 'aeiouAEIOUnN'), '\s+', ' ', 'g')) as n2
  from archivo a
