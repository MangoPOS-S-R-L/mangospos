    w(",\n".join(
        "  (%s, %s, %s, %s, %s)" % (q(i["sku"]), q(i["name"]), q(i["cat"]),
                                    num(i["price"]), num(i["cost"]))
        for i in items) + ";")
    w("")
    w("-- Catalogo actual del negocio, con el nombre normalizado.")
    w("create temp table _actual on commit drop as")
    w("select mi.id, mi.name, mi.price, mi.cost, mi.sku, mi.is_active,")
    w("       c.name as cat, %s as k" % (NORM % "mi.name"))
    w("from public.menu_items mi")
    w("left join public.categories c on c.id = mi.category_id")
    w("where mi.business_id = '%s'::uuid;" % BID)
    w("")
