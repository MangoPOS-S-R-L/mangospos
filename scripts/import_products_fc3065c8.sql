create temp table _arch on commit drop as
select s.*, upper(btrim(regexp_replace(translate(s.name, 'ÁÉÍÓÚÜÑÀÈÌÒÙÂÊÎÔÛáéíóúüñàèìòùâêîôû', 'AEIOUUNAEIOUAEIOUaeiouunaeiouaeiou'), '\s+', ' ', 'g'))) as k from _stage s;
create index on _arch (k);

-- ---------------------------------------------------------------------------
-- 3) El catalogo actual, con la misma clave
-- ---------------------------------------------------------------------------
create temp table _actual on commit drop as
select mi.id, mi.name, mi.sku, upper(btrim(regexp_replace(translate(mi.name, 'ÁÉÍÓÚÜÑÀÈÌÒÙÂÊÎÔÛáéíóúüñàèìòùâêîôû', 'AEIOUUNAEIOUAEIOUaeiouunaeiouaeiou'), '\s+', ' ', 'g'))) as k
from public.menu_items mi
where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid;
create index on _actual (k);

-- ---------------------------------------------------------------------------
-- 4) Regla A — emparejamiento 1:1 sin ambiguedad
-- ---------------------------------------------------------------------------
create temp table _match on commit drop as
select a.sku, x.id as item_id
from _arch a
join _actual x on x.k = a.k
where (select count(*) from _arch   a2 where a2.k = a.k) = 1
  and (select count(*) from _actual x2 where x2.k = a.k) = 1;

-- ---------------------------------------------------------------------------
-- 5) ACTUALIZA los emparejados y les graba el sku del archivo
-- ---------------------------------------------------------------------------
update public.menu_items mi
set sku         = s.sku,
    name        = s.name,
    price       = s.price,
    cost        = s.cost,
    category_id = c.id,
    tax_mode    = 'exclusive',
    is_active   = true,
    updated_at  = now()
from _match m
join _stage s on s.sku = m.sku
left join lateral (
  select c2.id from public.categories c2
  where c2.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid and c2.name = s.cat
  order by c2.created_at asc limit 1
) c on true
where mi.id = m.item_id;

-- ---------------------------------------------------------------------------
-- 6) Regla B — INSERTA solo los nombres que NO existen en el catalogo.
--    Este `not exists` es el candado anti-duplicados.
-- ---------------------------------------------------------------------------
insert into public.menu_items
  (business_id, category_id, name, price, cost, tax_mode, sku, is_active)
select 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid, c.id, a.name, a.price, a.cost, 'exclusive', a.sku, true
from _arch a
left join lateral (
  select c2.id from public.categories c2
  where c2.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid and c2.name = a.cat
  order by c2.created_at asc limit 1
) c on true
where not exists (select 1 from _actual x where x.k = a.k);

-- ---------------------------------------------------------------------------
-- 7) Impuestos ITBIS + LEY a los productos del archivo (los actualizados y
--    los nuevos; ambos ya tienen sku). Solo agrega los que falten.
-- ---------------------------------------------------------------------------
insert into public.menu_item_taxes (item_id, tax_id)
select mi.id, tt.id
from public.menu_items mi
join _stage s on s.sku = mi.sku
cross join _tax_cfg cfg
join lateral (
  select t.id from public.taxes t
  where t.business_id = mi.business_id
    and upper(btrim(t.name)) = upper(btrim(cfg.name))
    and coalesce(t.is_active, true)
  order by t.created_at asc limit 1
) tt on true
where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid
  and not exists (
    select 1 from public.menu_item_taxes x
    where x.item_id = mi.id and x.tax_id = tt.id
  );

-- ---------------------------------------------------------------------------
-- 8) Menu: usa el que ya tiene el negocio ('Menu Principal'); si no hubiera
--    ninguno, crea uno. Sin fila en menu_item_links no aparece en la caja.
-- ---------------------------------------------------------------------------
insert into public.menus (id, business_id, name, is_active)
select gen_random_uuid(), 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid, 'MENU PRINCIPAL', true
where not exists (
  select 1 from public.menus m
  where m.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid and coalesce(m.is_active, true)
);

