def parse_rows(block):
    rows = []
    for ln in block.strip().splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        parts = ln.split("|")
        code, tax, cost, price, cat, name = (p.strip() for p in parts)
        rows.append((code, tax, float(cost), float(price), cat, name))
    return rows


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def num(x):
    # entero si es entero, si no 2 decimales
    if x == int(x):
        return str(int(x))
    return f"{x:.2f}"


def main():
    rows = parse_rows(DATA)

    # validaciones
    seen = {}
    for i, (code, tax, cost, price, cat, name) in enumerate(rows, 1):
        assert tax in TAXES, f"tax desconocido {tax} en fila {i}"
        assert cat in CATEGORIES, f"categoria desconocida {cat} en fila {i} ({name})"
        assert price > 0, f"precio<=0 en fila {i} ({name})"
        if code in seen:
            raise SystemExit(f"CODIGO duplicado: {code} (fila {i} y {seen[code]})")
        seen[code] = i

    out = []
    w = out.append
    w("-- =============================================================================")
    w("-- Seed de productos: LAS TRES CRUCES FOOD SHOP")
    w(f"-- Business: {BUSINESS}")
    w("-- =============================================================================")
    w(f"-- {len(rows)} productos en {len(CATEGORIES)} categorias. Generado por scripts/gen_tres_cruces.py")
    w("-- Fuente: PDF 'Listado de Productos las tres cruces food shop'.")
    w("--")
    w("-- Mapeo: name=DESCRIPCION (limpia), price=P.PUBLICO, cost=P.COMPRA,")
    w("--        sku=CODIGO, barcode=CODIGO si es numerico, tax=IMPUESTO.")
    w("--")
    w("-- tax_mode='inclusive': el P.PUBLICO YA incluye ITBIS (precio de gondola).")
    w("-- Se ligan impuestos via menu_item_taxes: EXENTO=0%, ITBIS 18%, ITBIS 16%.")
    w("-- Sin tracking de inventario (catalogo). Activar por producto desde el form.")
    w("--")
    w("-- Idempotente: re-ejecutar no duplica (guarda por sku / nombre de tax/categoria).")
    w("-- =============================================================================")
    w("")
    w("begin;")
    w("")

    # 1) Categorias
    w("-- ----------------------------------------------------------------------------")
    w("-- 1) Categorias")
    w("-- ----------------------------------------------------------------------------")
    for pos, cat in enumerate(CATEGORIES):
        w("insert into public.categories (id, business_id, name, position, is_active)")
        w(f"select gen_random_uuid(), '{BUSINESS}', {sql_str(cat)}, {pos}, true")
        w("where not exists (")
        w("  select 1 from public.categories")
        w(f"  where business_id = '{BUSINESS}' and name = {sql_str(cat)}")
        w(");")
    w("")

    # 2) Impuestos
    w("-- ----------------------------------------------------------------------------")
    w("-- 2) Impuestos (ITBIS). Solo columnas base; el resto toma defaults")
    w("--    (apply_on_* = true, is_service_fee = false).")
    w("-- ----------------------------------------------------------------------------")
    for code, (tname, rate) in TAXES.items():
        w("insert into public.taxes (id, business_id, name, rate, is_active)")
        w(f"select gen_random_uuid(), '{BUSINESS}', {sql_str(tname)}, {rate}, true")
        w("where not exists (")
        w("  select 1 from public.taxes")
        w(f"  where business_id = '{BUSINESS}' and name = {sql_str(tname)}")
        w(");")
    w("")

    # 3) Tabla temporal con los productos
    w("-- ----------------------------------------------------------------------------")
    w("-- 3) Productos -> tabla temporal -> menu_items + menu_item_taxes")
    w("-- ----------------------------------------------------------------------------")
    w("create temporary table tmp_tc (")
    w("  sku text, name text, price numeric(12,2), cost numeric(12,2),")
    w("  taxname text, catname text, is_bev boolean, has_prep boolean, pos int")
    w(") on commit drop;")
    w("")
    w("insert into tmp_tc (sku, name, price, cost, taxname, catname, is_bev, has_prep, pos) values")
    vals = []
    for i, (code, tax, cost, price, cat, name) in enumerate(rows):
        tname = TAXES[tax][0]
        costsql = "null" if cost == 0 else num(cost)
        isbev = "true" if cat in BEVERAGE_CATS else "false"
        hasprep = "true" if cat in PREP_CATS else "false"
        vals.append(
            f"  ({sql_str(code)}, {sql_str(name)}, {num(price)}, {costsql}, "
            f"{sql_str(tname)}, {sql_str(cat)}, {isbev}, {hasprep}, {i})"
        )
    w(",\n".join(vals) + ";")
    w("")

    # 4) Insert a menu_items
    w("-- 4) Insert productos (idempotente por sku). barcode = sku si es numerico.")
    w("insert into public.menu_items")
    w("  (business_id, category_id, name, price, cost, sku, barcode,")
    w("   tax_mode, is_active, is_beverage, has_prep, position)")
    w("select")
    w(f"  '{BUSINESS}', c.id, t.name, t.price, t.cost, t.sku,")
    w("  case when t.sku ~ '^[0-9]+$' then t.sku else null end,")
    w("  'inclusive', true, t.is_bev, t.has_prep, t.pos")
    w("from tmp_tc t")
    w(f"join public.categories c on c.business_id = '{BUSINESS}' and c.name = t.catname")
    w("where not exists (")
    w("  select 1 from public.menu_items mi")
    w(f"  where mi.business_id = '{BUSINESS}' and mi.sku = t.sku")
    w(");")
    w("")

    # 5) Link menu_item_taxes
    w("-- 5) Ligar cada producto a su impuesto (idempotente).")
    w("insert into public.menu_item_taxes (item_id, tax_id)")
    w("select mi.id, tx.id")
    w("from tmp_tc t")
    w(f"join public.menu_items mi on mi.business_id = '{BUSINESS}' and mi.sku = t.sku")
    w(f"join public.taxes tx on tx.business_id = '{BUSINESS}' and tx.name = t.taxname")
    w("where not exists (")
    w("  select 1 from public.menu_item_taxes l")
    w("  where l.item_id = mi.id and l.tax_id = tx.id")
    w(");")
    w("")
    w("commit;")
    w("")
    w("-- Verificacion rapida (descomentar):")
    w(f"-- select count(*) from public.menu_items where business_id = '{BUSINESS}';")

    print("\n".join(out))


if __name__ == "__main__":
    main()
