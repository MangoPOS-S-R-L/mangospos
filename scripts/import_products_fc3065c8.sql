from public.menu_items mi
join _stage s on s.sku = mi.sku
left join public.categories c on c.id = mi.category_id
join lateral (
  select m2.id from public.menus m2
  where m2.business_id = mi.business_id and coalesce(m2.is_active, true)
  order by m2.created_at asc limit 1
) m on true
where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid
  and not exists (
    select 1 from public.menu_item_links l
    where l.item_id = mi.id and l.menu_id = m.id
  );

-- ---------------------------------------------------------------------------
-- 9) Control
--    en_archivo debe ser 625. sin_impuesto / sin_categoria / fuera_del_menu
--    / no_exclusive deben dar 0.
--    ambiguos_sin_tocar = los de la regla C: se listan en el paso 10.
-- ---------------------------------------------------------------------------
select
  (select count(*) from _arch)  as en_archivo,
  (select count(*) from _match) as actualizados,
  (select count(*) from _arch a
    where not exists (select 1 from _actual x where x.k = a.k)) as insertados,
  (select count(*) from _arch a
    where not exists (select 1 from _match m where m.sku = a.sku)
      and exists (select 1 from _actual x where x.k = a.k)) as ambiguos_sin_tocar,
  (select count(*) from public.menu_items
    where business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid) as total_catalogo,
  (select count(*) from public.categories
    where business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid) as categorias,
  (select count(*) from public.menu_items mi join _stage s on s.sku = mi.sku
    where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid and mi.tax_mode <> 'exclusive') as no_exclusive,
  (select count(*) from public.menu_items mi join _stage s on s.sku = mi.sku
    where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid
      and not exists (select 1 from public.menu_item_taxes x where x.item_id = mi.id)
   ) as sin_impuesto,
  (select count(*) from public.menu_items mi join _stage s on s.sku = mi.sku
    where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid and mi.category_id is null) as sin_categoria,
  (select count(*) from public.menu_items mi join _stage s on s.sku = mi.sku
    where mi.business_id = 'fc3065c8-cb40-45ad-bec1-aecb388001c1'::uuid
      and not exists (select 1 from public.menu_item_links l where l.item_id = mi.id)
   ) as fuera_del_menu;

-- ---------------------------------------------------------------------------
-- 10) Regla C — los que quedaron SIN TOCAR por nombre ambiguo.
--     Resuelvelos a mano (renombra o borra el repetido) y vuelve a correr
--     este script: al desaparecer la ambiguedad entran solos.
-- ---------------------------------------------------------------------------
select a.sku as sku_archivo, a.name as nombre_archivo, a.cat as categoria_archivo,
       a.price as precio_archivo,
       (select count(*) from _arch   a2 where a2.k = a.k) as veces_en_archivo,
       (select count(*) from _actual x2 where x2.k = a.k) as veces_en_catalogo,
       (select string_agg(x3.name, '  ||  ') from _actual x3 where x3.k = a.k) as filas_del_catalogo
from _arch a
where not exists (select 1 from _match m where m.sku = a.sku)
  and exists (select 1 from _actual x where x.k = a.k)
order by a.cat, a.name;

