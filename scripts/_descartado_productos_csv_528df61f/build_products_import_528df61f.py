    w("create temp table _arch on commit drop as")
    w("select s.*, %s as k from _stage s;" % (NORM % "s.name"))
    w("")
    w("-- ---------------------------------------------------------------------------")
    w("-- 1) Resumen")
    w("-- ---------------------------------------------------------------------------")
    w("select")
    w("  (select count(*) from _arch)   as en_archivo,")
    w("  (select count(*) from _actual) as ya_cargados,")
    w("  (select count(*) from _arch a where exists (select 1 from _actual x where x.k = a.k))")
