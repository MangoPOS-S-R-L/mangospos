create temp table _res on commit drop as
select f.sku, c.id as item_id
from _fk f join _c c on c.k = upper(btrim(regexp_replace(translate(f.target, 'ÁÉÍÓÚÜÑÀÈÌÒÙÂÊÎÔÛáéíóúüñàèìòùâêîôû', 'AEIOUUNAEIOUAEIOUaeiouunaeiouaeiou'), '\s+', ' ', 'g')))
where f.target is not null
union
select f.sku, c.id
from _fk f join _c c on c.k = f.k
where f.target is null
  and (select count(*) from _fk f2 where f2.k = f.k and f2.target is null) = 1
  and (select count(*) from _c  c2 where c2.k = f.k) = 1;

