  ('ITBIS'),
  ('LEY');

do $$
declare
  v_business uuid := 'fc3065c8-cb40-45ad-bec1-aecb388001c1';
  v_missing  text;
  v_have     text;
begin
  if not exists (select 1 from public.businesses b where b.id = v_business) then
    raise exception 'El negocio % no existe', v_business;
  end if;

  select string_agg(cfg.name, ', ')
    into v_missing
  from _tax_cfg cfg
  where not exists (
    select 1 from public.taxes t
    where t.business_id = v_business
      and upper(btrim(t.name)) = upper(btrim(cfg.name))
      and coalesce(t.is_active, true)
  );
  if v_missing is not null then
    select string_agg(t.name || ' (' || t.rate || ')', ', ' order by t.name)
      into v_have
    from public.taxes t
    where t.business_id = v_business and coalesce(t.is_active, true);
    raise exception 'Faltan impuestos activos: %. El negocio tiene: %.', v_missing, coalesce(v_have, '(ninguno)');
  end if;
end $$;

