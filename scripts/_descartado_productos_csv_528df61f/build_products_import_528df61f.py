    w("       x.is_active      as activo")
    w("from _arch a")
    w("join _actual x on x.k = a.k")
    w("order by (x.price is distinct from a.price) desc, a.cat, a.name;")
    w("")
    w("-- ---------------------------------------------------------------------------")
    w("-- 4) NUEVOS — no existen hoy, se insertarian")
    w("-- ---------------------------------------------------------------------------")
    w("select a.sku, a.name, a.cat, a.price, a.cost")
